/**
 * Returns a deterministic word of the day based on any given date string 'YYYY-MM-DD'.
 * Uses a stable hash so the same day always returns the same word across reloads.
 */
export function getWordForDate(dateStr) {
  if (!dateStr) return ENGLISH_DAILY_WORDS[0];
  let hash = 0;
  for (let i = 0; i < dateStr.length; i++) {
    hash = (hash << 5) - hash + dateStr.charCodeAt(i);
    hash |= 0;
  }
  const index = Math.abs(hash) % ENGLISH_DAILY_WORDS.length;
  return ENGLISH_DAILY_WORDS[index];
}

/**
 * Speaks an English word out loud using browser speech synthesis with accent selection
 * @param {string} word - The word or phrase to pronounce
 * @param {'us' | 'uk'} [accent='us'] - Desired pronunciation accent
 */
export function speakWord(word, accent = 'us') {
  if (typeof window === 'undefined' || !('speechSynthesis' in window)) {
    console.warn('[English Daily] Web Speech API not supported in this browser.');
    return;
  }
  try {
    window.speechSynthesis.cancel(); // Stop any pending speech
    const utterance = new SpeechSynthesisUtterance(word);
    const voices = window.speechSynthesis.getVoices() || [];

    if (accent === 'uk') {
      utterance.lang = 'en-GB';
      const ukVoice = voices.find(v => 
        v.lang === 'en-GB' || 
        v.lang.includes('en-GB') || 
        v.name.toLowerCase().includes('british') || 
        v.name.toLowerCase().includes('uk') || 
        v.name.toLowerCase().includes('daniel') ||
        v.name.toLowerCase().includes('oliver')
      );
      if (ukVoice) utterance.voice = ukVoice;
    } else {
      utterance.lang = 'en-US';
      const usVoice = voices.find(v => 
        v.lang === 'en-US' || 
        v.lang.includes('en-US') || 
        v.name.toLowerCase().includes('united states') || 
        v.name.toLowerCase().includes('us') ||
        v.name.toLowerCase().includes('samantha') ||
        v.name.toLowerCase().includes('alex')
      );
      if (usVoice) utterance.voice = usVoice;
    }

    utterance.rate = 0.88; // Measured rate for clear articulation
    utterance.pitch = 1.0;
    window.speechSynthesis.speak(utterance);
  } catch (err) {
    console.warn('[English Daily] Speech error:', err);
  }
}

